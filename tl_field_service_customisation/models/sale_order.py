    @api.model_create_multi
    def create(self,val_list):
        res = super().create(val_list)
        res.assign_subscription_to_asset()
        for rec in res:
            if not rec.is_subscription:
                continue
            elif rec.origin_order_id and rec.origin_order_id.contract_id:
                line = self.env['service.contract.line'].create({
                    'sale_id': rec.id,
                    'contract_id': rec.origin_order_id.contract_id.id
                })
                rec.contract_line_id = line.id
            else:
                contract = self.env['service.contract'].create({
                    'sale_id': rec.id,
                })
                # rec.contract_id = contract.id
                line = self.env['service.contract.line'].create({
                    'sale_id': rec.id,
                    'contract_id': contract.id
                })
                rec.contract_line_id = line.id

        return res

    def write(self,vals_list):

        res = super().write(vals_list)
        self.assign_subscription_to_asset()
        return res


    def assign_subscription_to_asset(self):
        for rec in self:
            order = rec
            if rec.origin_order_id:
                order = rec.origin_order_id
            for asset in rec.subscription_customer_assets_ids:
                asset.subscription_id = order.id

    @api.depends('partner_id')
    def _compute_available_address_ids(self):
        Partner = self.env['res.partner']

        for rec in self:
            partners = Partner.browse()
            delivery_partners = Partner.browse()
            invoice_partners = Partner.browse()

            if rec.partner_id:
                partners |= rec.partner_id

                if rec.partner_id.parent_id:
                    partners |= rec.partner_id.parent_id
                    delivery_partners |= rec.partner_id.parent_id.child_ids.filtered(lambda p: p.type == 'delivery')
                    invoice_partners |= rec.partner_id.parent_id.child_ids.filtered(lambda p: p.type == 'invoice')

                delivery_partners |= rec.partner_id.child_ids.filtered(lambda p:p.type == 'delivery')
                invoice_partners |= rec.partner_id.child_ids.filtered(lambda p:p.type == 'invoice')


                delivery_partners |= partners
                invoice_partners |= partners

            rec.available_shipping_ids = delivery_partners
            rec.available_invoice_ids = invoice_partners

    def prepare_renewal_order(self):
        self.ensure_one()

        if not self.contract_id or not self.contract_id.signed_document:
            raise UserError(self.env._(
                "You cannot renew this subscription because the contract is not signed."
            ))

        res = super().prepare_renewal_order()
        renew_order = self.browse(res.get('res_id')) if res.get('res_id') else False

        if renew_order:
            if self.subscription_customer_assets_ids:
                renew_order.subscription_customer_assets_ids = [
                    (6, 0, self.subscription_customer_assets_ids.ids)
                ]

            if self.sign_template_id:
                renew_order.sign_template_id = self.sign_template_id

        return res

    def action_confirm(self):
        res = super().action_confirm()
        self._create_interventions_for_year()
        return res

    @api.depends('sign_request_id.request_item_ids.state')
    def _compute_user_signed(self):
        user_role = self.env['service.contract']._get_sign_role('user')
        for rec in self:
            rec.user_signed = any(
                item.role_id == user_role and item.state == 'completed'
                for item in rec.sign_request_id.request_item_ids
            )


    def _get_intervention_start_datetimes(self, count):
        """Spread `count` interventions over the contract year, at 9:00 (user tz)."""
        self.ensure_one()
        base_date = self.start_date or fields.Date.context_today(self)
        tz = ZoneInfo(self.user_id.tz or self.env.user.tz or 'UTC')
        res = []
        for index in range(count):
            day = base_date + relativedelta(months=(index * 12) // max(count, 1))
            local_dt = datetime.combine(day, time(9, 0), tzinfo=tz)
            res.append(local_dt.astimezone(ZoneInfo('UTC')).replace(tzinfo=None))
        return res

    def _prepare_intervention_values(self, line, start_datetime, hours, assets, name):
        self.ensure_one()
        product = line.product_id
        resources = self.user_id.employee_ids.filtered(lambda e: e.company_id == self.company_id).resource_id[:1]
        return {
            'name': name,
            'sale_line_id': line.id,
            'partner_id': (self.partner_shipping_id or self.partner_id).id,
            'role_id': product.planning_role_id.id,
            'worksheet_template_id': product.worksheet_template_id.id,
            'start_datetime': start_datetime,
            'end_datetime': start_datetime + timedelta(hours=hours),
            'allocated_hours': hours,
            'resource_ids': [fields.Command.set(resources.ids)],
            'customer_assets_ids': [fields.Command.set(assets.ids)],
            'company_id': self.company_id.id,
        }

    def _create_interventions_for_year(self):
        """Create all Field Service interventions (planning.slot) of the subscription for
        the current contract year: `number_of_services_per_year` per field service product,
        either shared by all the customer assets or one per asset (product setting)."""
        Slot = self.env['planning.slot'].sudo()
        for rec in self:
            if not rec.is_subscription:
                continue
            created_slots = Slot
            assets = rec.subscription_customer_assets_ids
            year = (rec.start_date or fields.Date.context_today(rec)).year
            for line in rec.order_line.filtered(lambda l: l._is_contract_intervention_line()):
                product = line.product_template_id
                num_services = int(product.number_of_services_per_year or 1)
                start_datetimes = rec._get_intervention_start_datetimes(num_services)
                per_asset = product.fsm_task_creation_mode == 'per_asset' and assets
                groups = [(asset, f" - {asset.name}") for asset in assets] if per_asset else [(assets, "")]
                total = num_services * len(groups)
                hours = max(line.planning_hours_to_plan / total if total else 0.0, 1.0)
                vals_list = []
                for group_assets, suffix in groups:
                    for service, start_dt in enumerate(start_datetimes):
                        name = f"{rec.name} - {rec.partner_id.display_name} - {product.display_name}{suffix} - {year} - Service-{service + 1}"
                        vals_list.append(rec._prepare_intervention_values(line, start_dt, hours, group_assets, name))
                if vals_list:
                    created_slots |= Slot.create(vals_list)

            if created_slots:
                items = Markup('').join(Markup("<li>%s</li>") % slot.display_name for slot in created_slots)
                rec.message_post(
                    body=Markup("<b>%s</b><br/><span>%s <b>%s</b></span><br/><br/><b>%s</b><ul>%s</ul>") % (
                        self.env._("Field Service Interventions Created"),
                        self.env._("Interventions created for the year from subscription:"),
                        rec.name,
                        self.env._("Created Interventions:"),
                        items,
                    ),
                    message_type="comment",
                    subtype_xmlid="mail.mt_note",
                )

