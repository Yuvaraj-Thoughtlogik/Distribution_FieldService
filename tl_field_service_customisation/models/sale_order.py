class SaleOrderLine(models.Model):
    _inherit = 'sale.order.line'

    def _is_contract_intervention_line(self):
        """Field service lines of a subscription: their interventions are generated by
        `sale.order._create_interventions_for_year` (number of services per year)."""
        self.ensure_one()
        return self.order_id.is_subscription and self.product_id.planning_enabled and not self.display_type

    def _planning_slot_generation(self):
        contract_lines = self.filtered(lambda sol: sol._is_contract_intervention_line())
        return super(SaleOrderLine, self - contract_lines)._planning_slot_generation()


